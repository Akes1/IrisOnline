/// 원소
/// 단순히 생성자와 소멸자를 호출하는 역할을 한다.
template<class T>
class tElement
{
public:
	/// 생성자를 호출
	static void Construct( T* p, const T& val )
	{
		new (p) T( val );
	}

	/// 소멸자를 호출
	static void Destroy( T* p )
	{
		p->~T();
	}
};
